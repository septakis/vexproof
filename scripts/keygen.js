#!/usr/bin/env node
// SPDX-License-Identifier: MIT
// One-time: create the license signing keypair.
// Writes the PRIVATE key to .keys/ (never commit or publish it) and the public key into src/pro/license-key.js.
import { generateKeyPairSync } from 'node:crypto';
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';

const force = process.argv.includes('--force');
if (existsSync('.keys/license-private.pem') && !force) {
  console.error('.keys/license-private.pem already exists. Re-keying invalidates every license you have issued; pass --force if you mean it.');
  process.exit(1);
}
const { publicKey, privateKey } = generateKeyPairSync('ed25519');
mkdirSync('.keys', { recursive: true });
writeFileSync('.keys/license-private.pem', privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
const pub = publicKey.export({ type: 'spki', format: 'pem' });
writeFileSync('src/pro/license-key.js', `// SPDX-License-Identifier: LicenseRef-vexproof-Pro\n// Part of vexproof Pro. Not MIT: see LICENSE.md in this directory.\n// Public half of the license signing key. Generated by scripts/keygen.js.\nexport const PUBLIC_KEY_PEM = ${JSON.stringify(pub)};\n`);
console.log('Wrote .keys/license-private.pem (keep it offline, back it up) and src/pro/license-key.js');
